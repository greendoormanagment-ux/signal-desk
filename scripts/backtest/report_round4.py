"""Write backtest/round4-latest.md from the newest round4-*.json.  Usage: python report_round4.py RESULTS_DIR OUT_MD"""
import glob, json, os, sys

src, out_md = sys.argv[1], sys.argv[2]
f = sorted(glob.glob(os.path.join(src, "round4-2*.json")))[-1]
R = json.load(open(f))
P = R["periods"]
g = lambda d, *k: (lambda x: "–" if x is None else x)(__import__("functools").reduce(lambda a, b: (a or {}).get(b), k, d))
L = [f"# Round 4 — fixing the weaknesses ({R['asOf']})", "",
     f"**Data:** {R['mode']} · {R['stocks']} S&P 500 members (point in time), {R['with_sec']} with SEC EPS history · "
     f"cost {R['cost_per_side']*100:.2f}% per side · signals at the close, filled next open.",
     f"**Periods:** TUNE {P['tune'][0]} → {P['tune'][1]} · JUDGE (unseen) {P['judge'][0]} → {P['judge'][1]} · 2026 shown alone.", "",
     "**Pass bar (Playbook §4):** better average result per trade after costs than the live rules in BOTH periods, "
     "drawdown no worse (2-pt tolerance), at least 100 trades in the judge period. Beating SPY is not required — but it is shown.", ""]
if R["mode"].startswith("free"):
    L += ["> ⚠ **Free data:** companies that failed or were bought out are missing, so every result is flattered. "
          "Treat this as a preview; the EODHD run is the real test.", ""]
L += ["| SPY | CAGR | max drawdown |", "| --- | --- | --- |"]
for k in ("tune", "judge", "2026"):
    L.append(f"| {k} | {g(R, 'spy', k, 'cagr_%')}% | {g(R, 'spy', k, 'max_dd_%')}% |")
rd = R.get("regime_days_%", {})
L += ["", f"Regime in the judge period: full size {rd.get('full')}% of days · half {rd.get('half')}% · no new buys {rd.get('none')}%.", "",
      "## Results", "",
      "Avg R = average result per trade in units of the risk taken, after costs (0.10 = earned 10% of what it risked). "
      "Gave back = how many R a trade that reached +1R gave back before it was sold (lower = better selling). "
      "Portfolio = $100k, 10 positions, 1% risk each (half/none under regime sizing).", "",
      "| Variant | Trades (tune / judge) | Avg R tune | Avg R judge | Win % judge | Gave back (R) | Portfolio CAGR judge (MC range) | Max DD judge | vs SPY judge | Passes bar |",
      "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
for v in R["variants"]:
    t, j = v["periods"]["tune"], v["periods"]["judge"]
    mc = j["mc_cagr"]
    L.append(f"| {v['label']} | {g(t,'signals','trades')} / {g(j,'signals','trades')} | {g(t,'signals','avg_R_net')} | **{g(j,'signals','avg_R_net')}** | "
             f"{g(j,'signals','win_%')} | {g(j,'signals','gave_back_R_after_+1R')} | {g(j,'portfolio','cagr_%')}% ({mc['low']} to {mc['high']}) | "
             f"{g(j,'portfolio','max_dd_%')}% | {g(j,'portfolio','excess_cagr_%')} pts | {'—' if 'passes_bar' not in v else ('✅' if v['passes_bar'] else '✗')} |")
L += ["", "## 2026 so far (not used for any decision)", "", "| Variant | Trades | Avg R | CAGR |", "| --- | --- | --- | --- |"]
for v in R["variants"]:
    y = v["periods"]["2026"]
    L.append(f"| {v['label']} | {g(y,'signals','trades')} | {g(y,'signals','avg_R_net')} | {g(y,'portfolio','cagr_%')}% |")
b = R["variants"][0]["periods"]["judge"]
L += ["", "## Why trades ended (live rules, judge period)", "", "| Exit | Trades |", "| --- | --- |"]
L += [f"| {k} | {n} |" for k, n in b.get("exit_reasons", {}).items()]
L += ["", "## Uncertainty (judge period, block bootstrap of monthly excess return vs SPY)", "",
      "| Variant | 5th pct | median | 95th pct | % of resamples above zero |", "| --- | --- | --- | --- | --- |"]
for v in R["variants"]:
    bs = v["periods"]["judge"].get("bootstrap_vs_spy") or {}
    L.append(f"| {v['label']} | {bs.get('excess_p5_%','–')} | {bs.get('excess_median_%','–')} | {bs.get('excess_p95_%','–')} | {bs.get('share_above_zero_%','–')} |")
L += ["", "_Generated by scripts/backtest/run_round4.py + report_round4.py. One change at a time vs the live rules; "
      "the v3 rows combine the layers. Nothing here changes the live app._"]
open(out_md, "w").write("\n".join(L) + "\n")
print("wrote", out_md)
