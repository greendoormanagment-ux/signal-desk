"""Write the Round 5 report from the newest round5-*.json.  Usage: python report_round5.py RESULTS_DIR OUT_MD"""
import glob, json, os, sys

src, out_md = sys.argv[1], sys.argv[2]
R = json.load(open(sorted(glob.glob(os.path.join(src, "round5-2*.json")))[-1]))
P = R["periods"]
g = lambda d, *k: (lambda x: "–" if x is None else x)(__import__("functools").reduce(lambda a, b: (a or {}).get(b), k, d))
L = [f"# Round 5 — can Signal Desk beat SPY? ({R['asOf']})", "",
     f"**Data:** {R['mode']} · {R['stocks']} S&P 500 members (point in time) · cost {R['cost_per_side']*100:.2f}% per side "
     f"+ {R['idle_switch_cost']*100:.2f}% per SPY switch · signals at the close, filled next open.",
     f"**Periods:** TUNE {P['tune'][0]} → {P['tune'][1]} · JUDGE (unseen) {P['judge'][0]} → {P['judge'][1]} · 2026 shown alone.", "",
     "**What's new:** *idle SPY* = money not in a stock stays invested in SPY instead of cash (core + satellite in one account). "
     "*Combined* = Round 1's breakout + earnings-gap + pullback system with every exit on the 50-day line.", "",
     "**Pass bar (set before the run):** beat SPY in BOTH tune and judge (median of 10 random-order runs), ≥ 70% of judge-period "
     "bootstrap resamples above zero, and max drawdown no worse than SPY's + 5 points.", ""]
if R["mode"].startswith("free"):
    L += ["> ⚠ **Free data:** companies that failed or were bought out are missing, so stock-picking results are flattered "
          "(SPY is not). Treat a pass here as 'worth the paid test', not as proof.", ""]
L += ["| SPY (price) | CAGR | max drawdown |", "| --- | --- | --- |"]
L += [f"| {k} | {g(R,'spy',k,'cagr_%')}% | {g(R,'spy',k,'max_dd_%')}% |" for k in ("tune", "judge", "2026")]
L += ["", "## Results", "",
      "| Variant | In stocks (judge) | CAGR tune (vs SPY) | CAGR judge (vs SPY) | Judge MC range | Max DD judge | Bootstrap % above SPY | Passes |",
      "| --- | --- | --- | --- | --- | --- | --- | --- |"]
for v in R["variants"]:
    t, j = v["periods"]["tune"], v["periods"]["judge"]
    bs = j.get("bootstrap_vs_spy") or {}
    L.append(f"| {v['label']} | {g(j,'avg_in_stocks_%')}% | {g(t,'mc','cagr_median')}% ({g(t,'mc','excess_median')}) | "
             f"**{g(j,'mc','cagr_median')}% ({g(j,'mc','excess_median')})** | {g(j,'mc','cagr_low')} to {g(j,'mc','cagr_high')} | "
             f"{g(j,'portfolio','max_dd_%')}% | {bs.get('share_above_zero_%','–')} | {'✅' if v.get('passes_bar') else '✗'} |")
L += ["", "## 2026 so far (not used for decisions)", "", "| Variant | CAGR | vs SPY |", "| --- | --- | --- |"]
L += [f"| {v['label']} | {g(v,'periods','2026','mc','cagr_median')}% | {g(v,'periods','2026','mc','excess_median')} |" for v in R["variants"]]
L += ["", "_CAGR = median of 10 runs with random same-day order (luck check). 'In stocks' = average share of the account held in "
      "stocks; the rest is cash (controls) or SPY (idle-SPY rows). Generated by scripts/backtest/run_round5.py._"]
open(out_md, "w").write("\n".join(L) + "\n")
print("wrote", out_md)
