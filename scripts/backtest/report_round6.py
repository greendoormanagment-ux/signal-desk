"""Write the Round 6 report from the newest round6-*.json.  Usage: python report_round6.py RESULTS_DIR OUT_MD"""
import glob, json, os, sys

src, out_md = sys.argv[1], sys.argv[2]
R = json.load(open(sorted(glob.glob(os.path.join(src, "round6-2*.json")))[-1]))
f = lambda x, s="": "–" if x is None else f"{x}{s}"
name = lambda c: f"{c['entry']} · {c['setup']} · {c['exit']} · {c['market']} · {c['reentry']}"
C = R["combos"]
L = [f"# Round 6 — best small combination of rules ({R['asOf']})", "",
     f"**Data:** {R['mode']} · {R['stocks']} S&P 500 members (point in time) · cost {R['cost_per_side']*100:.2f}% per side · "
     "idle money in SPY · signals at the close, filled next open.",
     f"**Periods:** TUNE {R['tune'][0]} → {R['tune'][1]} (used to choose) · JUDGE {R['judge'][0]} → {R['judge'][1]} "
     "(opened only for the top 3) · 2026 shown alone.", "",
     "**Search:** 4 entry filters × 2 setup choices × 4 exits × 3 market rules × re-entry on/off = 192 combinations. "
     "*Re-entry* = after any sale, buy back within 40 sessions if the stock closes above its high since the sale, above the "
     "50-day, on 1.2× volume, not rated SELL, market not in CORRECTION (max 2 buy-backs in a row).", "",
     "**Pass bar (raised because 192 combinations were tried):** beat SPY in tune AND judge, ≥ 80% of judge bootstrap "
     "resamples above zero, judge drawdown no worse than SPY's + 5 points.", ""]
if R["mode"].startswith("free"):
    L += ["> ⚠ **Free data:** failed/bought-out companies are missing, so stock picking is flattered. "
          "A pass here means 'worth the paid EODHD test', not proof.", ""]
L += [f"**{R['beat_spy_in_tune']} of {len(C)} combinations beat SPY in the tune years.**", "",
      "| SPY | CAGR | max drawdown |", "| --- | --- | --- |"]
L += [f"| {k} | {f(R['spy'][k].get('cagr_%'), '%')} | {f(R['spy'][k].get('max_dd_%'), '%')} |" for k in ("tune", "judge", "2026")]
L += ["", "## Top 3 (chosen on tune only) + the live system", "",
      "| Combination | Rule changes | Tune vs SPY | Judge CAGR (vs SPY) | Judge range | Judge max DD | Bootstrap % | 2026 vs SPY | Passes |",
      "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
for c in R["top3"] + [dict(R["live_baseline"], changes_vs_live=0, passes_bar=None)]:
    j = c.get("judge") or {}; y = c.get("2026") or {}
    tag = " **(live today)**" if c.get("passes_bar") is None else ""
    L.append(f"| {name(c)}{tag} | {c['changes_vs_live']} | {f(c['tune']['excess_median'])} | **{f(j.get('cagr_median'), '%')} "
             f"({f(j.get('excess_median'))})** | {f(j.get('cagr_low'))} to {f(j.get('cagr_high'))} | {f(j.get('max_dd'), '%')} | "
             f"{f((j.get('bootstrap') or {}).get('share_above_zero_%'))} | {f(y.get('excess_median'))} | "
             f"{'–' if c.get('passes_bar') is None else ('✅' if c['passes_bar'] else '✗')} |")


def avg_by(key):
    out = {}
    for c in C:
        out.setdefault(c[key], []).append(c["tune"]["excess_median"])
    return sorted(((k, sum(v) / len(v), sum(1 for x in v if x > 0), len(v)) for k, v in out.items()), key=lambda r: -r[1])


L += ["", "## Which single choices helped most (tune years, averaged over every combination that used them)", ""]
for key, title in (("entry", "Entry filter"), ("setup", "Setups"), ("exit", "Exit"), ("market", "Market rule"), ("reentry", "Re-entry")):
    L += [f"**{title}:** " + " · ".join(f"{k} {a:+.1f} ({p}/{n} beat SPY)" for k, a, p, n in avg_by(key)), ""]
pairs = {}
for c in C:
    if c["reentry"] == "re-entry":
        o = next(d for d in C if d["reentry"] == "no re-entry" and all(d[k] == c[k] for k in ("entry", "setup", "exit", "market")))
        pairs.setdefault(c["exit"], []).append(c["tune"]["excess_median"] - o["tune"]["excess_median"])
L += ["**Re-entry effect by exit** (tune, re-entry minus no re-entry): " +
      " · ".join(f"{k} {sum(v)/len(v):+.1f}" for k, v in pairs.items()), ""]
L += ["## All 192 on tune (best first)", "", "| # | Combination | Tune vs SPY | Tune CAGR | Tune DD | Sub-periods vs SPY | Trades | Buy-backs |",
      "| --- | --- | --- | --- | --- | --- | --- | --- |"]
for i, c in enumerate(sorted(C, key=lambda c: -c["tune"]["excess_median"]), 1):
    t = c["tune"]
    L.append(f"| {i} | {name(c)} | {t['excess_median']} | {f(t['cagr'], '%')} | {f(t['max_dd'], '%')} | "
             f"{' / '.join(str(x) for x in t['sub_excess'])} | {t['trades']} | {t['reentries']} |")
L += ["", f"_Sub-periods: {' · '.join(a[:4] + '–' + b[:4] for a, b in R['sub_periods'])}. Tune vs SPY = median excess CAGR of 3 "
      "random same-day-order runs. Generated by scripts/backtest/run_round6.py._"]
open(out_md, "w").write("\n".join(L) + "\n")
print("wrote", out_md)
